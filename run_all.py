"""Run all four parts and generate every log / table used in the report.

    python run_all.py

Outputs (all generated by this run, nothing typed by hand):
    logs/partA_baseline.jsonl        structured event log, Part A
    logs/partB_exceptions.jsonl      structured event log, Part B
    logs/partC_retry.jsonl           structured event log, Part C
    logs/partD_fault_tolerant.jsonl  structured event log, Part D (final solution)
    logs/partC_attempt_log.csv       attempt log, Part C
    logs/partD_attempt_log.csv       attempt log, Part D
    results/checkpoints.json         checkpoints saved by Part D
    results/transactions_final.csv   final status of every transaction in each mode
    results/metrics.json             all metrics + Part E calculations
    results/before_after.md          Part E table
"""
import csv
import json
import os
import platform
import subprocess
from datetime import datetime

from ft.data import TRANSACTIONS
from ft.logs import AttemptLog, RunLog
from ft.processors import run_baseline, run_exception_handling, run_fault_tolerant, run_retry

ROOT = os.path.dirname(os.path.abspath(__file__))
LOGS = os.path.join(ROOT, "logs")
RESULTS = os.path.join(ROOT, "results")


def git_commit():
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                                       stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return "no-git"


def pct(x):
    return f"{x * 100:.2f}%"


def banner(title):
    print("\n" + "=" * 100 + f"\n{title}\n" + "=" * 100)


def main():
    os.makedirs(LOGS, exist_ok=True)
    os.makedirs(RESULTS, exist_ok=True)
    meta = {"started": datetime.now().isoformat(timespec="seconds"), "commit": git_commit(),
            "python": platform.python_version(), "source": "run_all.py + ft/*.py"}

    banner("PART A - Baseline (no fault tolerance)")
    a = run_baseline(TRANSACTIONS, RunLog("A_baseline", os.path.join(LOGS, "partA_baseline.jsonl")))

    banner("PART B - Exception handling (try/except + classification + continue)")
    b = run_exception_handling(TRANSACTIONS, RunLog("B_exceptions", os.path.join(LOGS, "partB_exceptions.jsonl")))

    banner("PART C - Retry mechanism (exact fault-rule policy)")
    c_att = AttemptLog()
    c = run_retry(TRANSACTIONS, RunLog("C_retry", os.path.join(LOGS, "partC_retry.jsonl")), c_att)
    c_att.to_csv(os.path.join(LOGS, "partC_attempt_log.csv"))

    banner("PART D - Retry + Checkpoint (every 5 successes) + Rollback (final solution)")
    d_att = AttemptLog()
    d = run_fault_tolerant(TRANSACTIONS, RunLog("D_fault_tolerant", os.path.join(LOGS, "partD_fault_tolerant.jsonl")),
                           d_att, cp_path=os.path.join(RESULTS, "checkpoints.json"))
    d_att.to_csv(os.path.join(LOGS, "partD_attempt_log.csv"))

    # ------------------------------------------------ final status per mode
    with open(os.path.join(RESULTS, "transactions_final.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["id", "amount_kzt", "failure_type", "A_baseline", "B_exceptions", "C_retry",
                    "D_fault_tolerant", "exception", "recovery_action_D"])
        for t in TRANSACTIONS:
            w.writerow([t.txn_id, t.amount, t.failure_type, a.status[t.txn_id], b.status[t.txn_id],
                        c.status[t.txn_id], d.status[t.txn_id], d.exception.get(t.txn_id, "-"),
                        d.recovery.get(t.txn_id, "-")])

    # ------------------------------------------------ Part E calculations
    faulty = [t for t in TRANSACTIONS if t.failure_type != "None"]
    recovered = [t.txn_id for t in faulty if d.status[t.txn_id].startswith("SUCCESS")]
    e = {
        "recovery_improvement_pp": round((d.completion_rate - a.completion_rate) * 100, 2),
        "recovery_rate_of_faulty": f"{len(recovered)}/{len(faulty)} = {pct(len(recovered) / len(faulty))}",
        "transaction_loss_reduction": pct((a.lost - d.lost) / a.lost),
        "amount_loss_reduction": pct((a.lost_amount - d.lost_amount) / a.lost_amount),
        "gain_exception_handling_txn": b.successful - a.successful,
        "gain_exception_handling_kzt": b.processed_amount - a.processed_amount,
        "gain_retry_txn": c.successful - b.successful,
        "gain_retry_kzt": c.processed_amount - b.processed_amount,
        "gain_checkpoint_txn": d.successful - c.successful,
        "consistency_C": c.ledger_consistent, "orphans_C": c.orphan_rows,
        "consistency_D": d.ledger_consistent, "orphans_D": d.orphan_rows,
        "recovered": recovered,
    }
    metrics = {"meta": meta, "A": a.summary(), "B": b.summary(), "C": c.summary(), "D": d.summary(),
               "checkpoints": d.checkpoints, "partE": e}
    meta["finished"] = datetime.now().isoformat(timespec="seconds")
    with open(os.path.join(RESULTS, "metrics.json"), "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2, ensure_ascii=False)

    rows = [
        ("Successful transactions", a.successful, d.successful, f"+{d.successful - a.successful}"),
        ("Failed / lost transactions", a.lost, d.lost, f"-{a.lost - d.lost} ({e['transaction_loss_reduction']} less)"),
        ("Lost amount (KZT)", f"{a.lost_amount:,}", f"{d.lost_amount:,}",
         f"-{a.lost_amount - d.lost_amount:,} ({e['amount_loss_reduction']} less)"),
        ("Retries", a.retries, d.retries, f"+{d.retries} (recovery attempts)"),
        ("Rollbacks", a.rollbacks, d.rollbacks, f"+{d.rollbacks} (consistent state kept)"),
        ("Completion rate", pct(a.completion_rate), pct(d.completion_rate), f"+{e['recovery_improvement_pp']} pp"),
    ]
    md = ["| Metric | Baseline | Fault-tolerant | Improvement |", "|---|---|---|---|"]
    md += [f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} |" for r in rows]
    with open(os.path.join(RESULTS, "before_after.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")

    banner("PART E - Before / After")
    print(f"{'Metric':<28}{'Baseline':>14}{'Fault-tolerant':>18}   Improvement")
    for r in rows:
        print(f"{r[0]:<28}{str(r[1]):>14}{str(r[2]):>18}   {r[3]}")
    print(f"\nAblation: A={a.successful}  B={b.successful}  C={c.successful}  D={d.successful} successful")
    print(f"Ledger consistent: B={b.ledger_consistent} {b.orphan_rows}  C={c.ledger_consistent} {c.orphan_rows}  "
          f"D={d.ledger_consistent} {d.orphan_rows}")
    print(f"Commit: {meta['commit']}   Python {meta['python']}")


if __name__ == "__main__":
    main()
